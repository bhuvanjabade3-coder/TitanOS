"""Terminal and process control. Every command is risk-classified before it can
run; nothing generated by a model executes silently unless it is read-only."""
from __future__ import annotations

import os
import signal
import subprocess
import time

import psutil

from .. import system
from ..core import ActionError, Ctx, Gate
from ..security.risk import Risk, classify
from .files import resolve

MAX_OUTPUT = 100_000
_SECRET_MARKERS = ("API_KEY", "TOKEN", "SECRET", "PASSWORD")


def clean_env() -> dict[str, str]:
    """The child never inherits TITAN's own credentials."""
    return {k: v for k, v in os.environ.items()
            if not k.startswith("TITAN_") and not any(m in k.upper() for m in _SECRET_MARKERS)}


def _cwd(ctx: Ctx, a: dict):
    p = resolve(ctx, a.get("cwd", "~"), must_exist=True)
    if not p.is_dir():
        raise ActionError(f"{p}: not a directory")
    return p


def g_run(ctx: Ctx, a: dict) -> Gate:
    if not a["command"].strip():
        raise ActionError("command is empty")
    _cwd(ctx, a)
    c = classify(a["command"])
    return Gate(c.risk, c.reasons, f"Run: {a['command'][:200]}")


def _kill_group(p: subprocess.Popen) -> None:
    try:
        os.killpg(p.pid, signal.SIGTERM)
        try:
            p.wait(timeout=3)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass


def _clip(s: str) -> tuple[str, bool]:
    return (s, False) if len(s) <= MAX_OUTPUT else (s[:MAX_OUTPUT], True)


def run(ctx: Ctx, a: dict) -> dict:
    command, cwd = a["command"], _cwd(ctx, a)
    timeout = max(1, min(int(a.get("timeout", 60)), 3600))
    popen = dict(cwd=cwd, env=clean_env(), stdin=subprocess.DEVNULL, text=True,
                 errors="replace", start_new_session=True)

    if a.get("background"):
        def job(ctl):
            p = subprocess.Popen(["/bin/bash", "-c", command], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, **popen)
            tail: list[str] = []
            import threading
            def watch():
                while p.poll() is None:
                    if ctl.cancel_event.wait(0.2):
                        _kill_group(p)
                        return
            threading.Thread(target=watch, daemon=True).start()
            for line in p.stdout:  # type: ignore[union-attr]
                tail.append(line)
                del tail[:-200]
                ctx.core.bus.publish("terminal.output", {"task_id": ctl.id, "line": line.rstrip("\n")})
                ctl.progress(0.0, line.strip()[:200])
            code = p.wait()
            ctl.check()
            out = {"command": command, "exit_code": code, "output": "".join(tail)}
            ctx.core.notifier.notify("task", f"Command {'finished' if code == 0 else f'failed ({code})'}", command[:200],
                                     "info" if code == 0 else "warning")
            if code != 0:
                raise RuntimeError(f"exit code {code}\n{''.join(tail[-20:])}")
            return out
        task = ctx.core.tasks.submit(f"$ {command[:80]}", job)
        return {"background": True, "task_id": task["id"]}

    start = time.monotonic()
    p = subprocess.Popen(["/bin/bash", "-c", command], stdout=subprocess.PIPE, stderr=subprocess.PIPE, **popen)
    timed_out = False
    try:
        out, err = p.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        _kill_group(p)
        out, err = p.communicate()
    out, t1 = _clip(out)
    err, t2 = _clip(err)
    return {"command": command, "cwd": str(cwd), "exit_code": None if timed_out else p.returncode,
            "stdout": out, "stderr": err, "timed_out": timed_out, "truncated": t1 or t2,
            "duration": round(time.monotonic() - start, 3)}


def classify_only(ctx: Ctx, a: dict) -> dict:
    return classify(a["command"]).to_dict()


def proc_list(ctx: Ctx, a: dict) -> list:
    return system.processes(min(int(a.get("limit", 50)), 500), a.get("sort", "memory"))


def g_kill(ctx: Ctx, a: dict) -> Gate:
    try:
        p = psutil.Process(int(a["pid"]))
        name = p.name()
    except psutil.Error:
        raise ActionError(f"No such process: {a['pid']}")
    if int(a["pid"]) in (1, os.getpid()):
        raise ActionError("refusing to kill init or TITAN Core itself")
    return Gate(Risk.HIGH, ["terminates a running process; unsaved work in it is lost"],
                f"Terminate process {a['pid']} ({name})")


def proc_kill(ctx: Ctx, a: dict) -> dict:
    try:
        p = psutil.Process(int(a["pid"]))
        name = p.name()
        p.kill() if a.get("force") else p.terminate()
    except psutil.NoSuchProcess:
        raise ActionError(f"No such process: {a['pid']}")
    except psutil.AccessDenied:
        raise ActionError(f"Permission denied for process {a['pid']} (owned by another user)")
    return {"pid": int(a["pid"]), "name": name, "signal": "KILL" if a.get("force") else "TERM"}


def register(reg) -> None:
    S, I, B = {"type": "string"}, {"type": "integer"}, {"type": "boolean"}
    reg.add("terminal.run", "terminal",
            "Run a shell command in the user's home (or cwd). Read-only commands run directly; anything that "
            "modifies the system pauses for user approval. Use background=true for long-running commands.",
            run, {"command": S, "cwd": S, "timeout": I, "background": B}, ["command"], gate=g_run)
    reg.add("terminal.classify", "terminal", "Classify a command's risk without running it", classify_only,
            {"command": S}, ["command"], readonly=True)
    reg.add("proc.list", "system", "List running processes sorted by memory or cpu", proc_list,
            {"limit": I, "sort": S}, readonly=True)
    reg.add("proc.kill", "system", "Terminate a process. Always requires user approval", proc_kill,
            {"pid": I, "force": B}, ["pid"], gate=g_kill)
